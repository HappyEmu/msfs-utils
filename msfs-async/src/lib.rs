#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_known_and_unknown_simconnect_exceptions() {
        assert_eq!(simconnect_exception_name(3), Some("UNRECOGNIZED_ID"));
        assert_eq!(simconnect_exception_name(46), Some("CAMERA_API"));
        assert_eq!(simconnect_exception_name(47), None);

        let exception = ServerException {
            code: 3,
            send_id: 10,
            index: 2,
        };
        assert!(exception.to_string().contains("UNRECOGNIZED_ID"));
        let error = Error::SimConnectException(exception);
        assert_eq!(
            std::error::Error::source(&error).unwrap().to_string(),
            "SimConnect exception UNRECOGNIZED_ID (3) for send ID 10 at argument 2"
        );
    }

    #[test]
    fn latest_subscription_options_are_explicit() {
        let options = SubscriptionOptions::new(RecurringPeriod::SimFrame).latest();
        assert_eq!(options.period, RecurringPeriod::SimFrame);
        assert_eq!(options.overflow, OverflowPolicy::Latest);
        assert!(options.changed_only);
        assert_eq!(options.limit, 0);
    }
}
