/// A server-side SimConnect exception received after an API call was submitted.
#[non_exhaustive]
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ServerException {
    /// Raw `SIMCONNECT_EXCEPTION` value.
    pub code: u32,
    /// SDK send ID associated with the failing call.
    pub send_id: u32,
    /// Zero-based index of the invalid argument, when supplied by the SDK.
    pub index: u32,
}

impl ServerException {
    /// Return the SDK name for this exception code, when known.
    pub fn code_name(&self) -> Option<&'static str> {
        simconnect_exception_name(self.code)
    }
}

impl fmt::Display for ServerException {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self.code_name() {
            Some(name) => write!(
                f,
                "SimConnect exception {name} ({}) for send ID {} at argument {}",
                self.code, self.send_id, self.index
            ),
            None => write!(
                f,
                "unknown SimConnect exception {} for send ID {} at argument {}",
                self.code, self.send_id, self.index
            ),
        }
    }
}

impl std::error::Error for ServerException {}

/// Errors produced by the asynchronous client or the SimConnect server.
#[non_exhaustive]
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum Error {
    /// A SimConnect function returned a failing HRESULT.
    HResult(i32),
    /// SimConnect reported an asynchronous server-side exception.
    SimConnectException(ServerException),
    /// A native Windows operation failed.
    Windows(u32),
    /// The data returned by SimConnect was shorter than the requested type.
    InvalidPacket { expected: usize, actual: usize },
    /// The received definition ID did not match the registered type.
    DefinitionMismatch { expected: u32, actual: u32 },
    /// A typed client-data handle belongs to a different SimConnect session.
    ClientDataSessionMismatch,
    /// An internal SimConnect identifier space has been exhausted.
    IdExhausted,
    /// A client-data definition contains an offset or size outside its Rust type.
    InvalidClientDataDefinition,
    /// An operation failed and its best-effort rollback failed as well.
    RollbackFailed {
        /// The error which caused rollback to begin.
        operation: Box<Error>,
        /// The error returned while attempting rollback.
        rollback: Box<Error>,
    },
    /// A definition or client name contained an interior NUL byte.
    InvalidCString,
    /// The driver's command or response channel closed unexpectedly.
    DriverStopped,
    /// The driver thread could not be started.
    ThreadStart(String),
}

impl fmt::Display for Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::HResult(value) => write!(f, "SimConnect HRESULT {value:#010x}"),
            Self::SimConnectException(exception) => fmt::Display::fmt(exception, f),
            Self::Windows(value) => write!(f, "Windows error {value}"),
            Self::InvalidPacket { expected, actual } => write!(
                f,
                "SimConnect packet is too short: expected {expected} bytes, received {actual}"
            ),
            Self::DefinitionMismatch { expected, actual } => write!(
                f,
                "SimConnect definition mismatch: expected {expected}, received {actual}"
            ),
            Self::ClientDataSessionMismatch => {
                f.write_str("the client-data area belongs to a different SimConnect session")
            }
            Self::IdExhausted => f.write_str("a SimConnect identifier space is exhausted"),
            Self::InvalidClientDataDefinition => {
                f.write_str("a client-data definition is outside its Rust type layout")
            }
            Self::RollbackFailed {
                operation,
                rollback,
            } => write!(
                f,
                "SimConnect operation failed ({operation}) and rollback also failed ({rollback})"
            ),
            Self::InvalidCString => f.write_str("a string contains an interior NUL byte"),
            Self::DriverStopped => f.write_str("the SimConnect driver has stopped"),
            Self::ThreadStart(message) => {
                write!(f, "could not start the SimConnect driver thread: {message}")
            }
        }
    }
}

impl std::error::Error for Error {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::SimConnectException(exception) => Some(exception),
            Self::RollbackFailed { operation, .. } => Some(operation),
            _ => None,
        }
    }
}

