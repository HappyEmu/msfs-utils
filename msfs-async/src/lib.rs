/// The position and orientation components controlled by SimConnect freeze events.
///
/// Freezing a component prevents the simulator from immediately overwriting
/// values a client writes for that component.
#[derive(Clone, Copy, Debug, Default, Eq, PartialEq)]
pub struct FreezeState {
    /// Freeze latitude and longitude.
    pub latitude_longitude: bool,
    /// Freeze altitude.
    pub altitude: bool,
    /// Freeze pitch, bank, and heading.
    pub attitude: bool,
}

/// A recurring cadence accepted by typed subscriptions.
///
/// Unlike the SDK's general `Period` type, this cannot represent one-shot or
/// disabled requests.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum RecurringPeriod {
    /// Deliver changes once per visual frame.
    VisualFrame,
    /// Deliver changes once per simulation frame.
    SimFrame,
    /// Deliver changes once per simulated second.
    Second,
}

/// Behavior when a subscription consumer cannot keep up with incoming data.
#[derive(Clone, Copy, Debug, Default, Eq, PartialEq)]
pub enum OverflowPolicy {
    /// Preserve queued values and discard newly arriving values while full.
    #[default]
    DropNewest,
    /// Retain only the most recently received value.
    Latest,
}

/// Configuration for a recurring simulation-object subscription.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct SubscriptionOptions {
    /// Delivery cadence.
    pub period: RecurringPeriod,
    /// Number of buffered values when using [`OverflowPolicy::DropNewest`].
    pub capacity: usize,
    /// Behavior when values arrive faster than they are consumed.
    pub overflow: OverflowPolicy,
    /// Request only values which changed since the previous delivery.
    pub changed_only: bool,
    /// Number of period events before delivery begins.
    pub origin: u32,
    /// Number of period events between deliveries.
    pub interval: u32,
    /// Maximum deliveries, or zero for no limit.
    pub limit: u32,
}

impl SubscriptionOptions {
    /// Default options for the given cadence.
    pub const fn new(period: RecurringPeriod) -> Self {
        Self {
            period,
            capacity: 32,
            overflow: OverflowPolicy::DropNewest,
            changed_only: true,
            origin: 0,
            interval: 0,
            limit: 0,
        }
    }

    /// Retain only the newest unread value.
    pub const fn latest(mut self) -> Self {
        self.overflow = OverflowPolicy::Latest;
        self
    }
}

impl FreezeState {
    /// Leave every component under simulation control.
    pub const NONE: Self = Self::new(false, false, false);

    /// Freeze position and attitude so a client can drive all of them.
    pub const ALL: Self = Self::new(true, true, true);

    /// Select individual position and attitude components to freeze.
    pub const fn new(latitude_longitude: bool, altitude: bool, attitude: bool) -> Self {
        Self {
            latitude_longitude,
            altitude,
            attitude,
        }
    }
}

/// A data definition which can safely be copied out of a SimConnect packet.
///
/// # Safety
///
/// Every bit pattern SimConnect can produce for `Self` must be valid, and the
/// type's layout must exactly match its [`DataDefinition`]. The type must not
/// contain references, owning pointers, or fields with destructors. Structures
/// containing Rust `bool` are not valid because SimConnect represents booleans
/// as 32-bit integers.
///
/// This implementation is normally generated by [`data_definition`].
#[cfg(windows)]
pub unsafe trait AsyncDataDefinition: DataDefinition + Copy + Send + 'static {}

/// A client-data definition which can safely cross the driver-thread boundary.
///
/// # Safety
///
/// `Self` must have a stable layout matching its [`ClientDataDefinition`], and
/// every bit pattern that another SimConnect client can write must be valid for
/// the type. [`Self::async_definitions`] must describe initialized field bytes
/// within the type and must never identify padding. Prefer `#[repr(C)]`
/// structures containing integer and float fields.
///
/// This implementation is normally generated by [`client_data_definition`].
#[cfg(windows)]
pub unsafe trait AsyncClientDataDefinition:
    ClientDataDefinition + Copy + Send + 'static
{
    #[doc(hidden)]
    fn async_definitions() -> Vec<(usize, usize, u32, f32)>;
}

